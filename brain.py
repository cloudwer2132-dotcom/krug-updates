def find(items, q, key="text"):
    q = q.lower().strip()
    if not q: return None
    for it in items:
        if q in it[key].lower(): return it
    c = difflib.get_close_matches(q, [i[key].lower() for i in items], 1, 0.5)
    return next((i for i in items if c and i[key].lower() == c[0]), None)

